export function getOmaniZoneForGovernorate(governorate: string): {
  zone: OmanAgroZone;
  labelAr: string;
} {
  const g = governorate || '';
  if (g.includes('ظفار')) {
    return { zone: 'dhofar', labelAr: 'ظفار والرياح الموسمية (الخريف)' };
  }
  if (g.includes('الداخلية') || g.includes('الظاهرة') || g.includes('البريمي') || g.includes('الوسطى') || g.includes('شمال الشرقية')) {
    // Interior oases + Hajar foothill conditions
    return { zone: 'interior', labelAr: 'الواحات الداخلية وجبال الحجر' };
  }
  if (g.includes('جبل')) {
    return { zone: 'mountains', labelAr: 'المرتفعات الجبلية الباردة' };
  }
  return { zone: 'coastal', labelAr: 'السهول الساحلية (الباطنة ومسقط والشرقية)' };
}

function slot(
  phase: CalendarActivityPhase,
  shortLabel: string,
  detail: string,
  irrigationFreq: string,
  alertPriority: 'high' | 'medium' | 'normal',
  suggestedAlertTitle: string,
  suggestedAlertBody: string
): MonthlyCropSlot {
  return {
    phase,
    shortLabel,
    detail,
    irrigationFreq,
    alertPriority,
    suggestedAlertTitle,
    suggestedAlertBody,
  };
}

